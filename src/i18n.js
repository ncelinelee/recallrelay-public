export function setLocale(next) {
  locale.value = next === 'ko' ? 'ko' : 'en'
  localStorage.setItem('recallrelay-locale', locale.value)
  document.documentElement.lang = locale.value === 'ko' ? 'ko' : 'en'
}

export function toggleLocale() {
  setLocale(locale.value === 'en' ? 'ko' : 'en')
}

function dynamicTranslate(text) {
  if (locale.value !== 'ko' || typeof text !== 'string') return text
  let s = text
  const replacements = [
    [/^(\d+) result\(s\) within current access scope\.$/, '$1개 결과가 현재 접근 범위에서 검색되었습니다.'],
    [/^(\d+) employee\(s\) in current scope\.$/, '현재 범위의 직원 $1명'],
    [/^(\d+) request\(s\) waiting for manager approval\.$/, '매니저 승인 대기 $1건'],
    [/^(\d+) part record\(s\)$/, '부품 기록 $1건'],
    [/^(\d+) campaign\(s\) · (.+)$/, '$1개 캠페인 · $2'],
    [/^Recall Case (.+)$/, '리콜 Case $1'],
    [/^Loading employees…$/, '직원 목록 불러오는 중…'],
    [/^Loading registration requests…$/, '가입 신청 불러오는 중…'],
    [/^Dealership (\d+)$/, '딜러십 $1'],
  ]
  for (const [pattern, replacement] of replacements) {
    if (pattern.test(s)) return s.replace(pattern, replacement)
  }
  return s
}

export function tr(value) {
  if (value === null || value === undefined) return value
  const text = String(value)
  if (locale.value !== 'ko') return text
  return ko[text] ?? dynamicTranslate(text)
}

export function trRole(roleLabel) {
  return tr(roleLabel)
}

